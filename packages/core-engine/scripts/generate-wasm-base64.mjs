#!/usr/bin/env node
// Generates a TS file exporting the built WASM binary as a base64 string —
// consumed by @kbach/react-native's nativeBridge.web.ts (Expo Web /
// react-native-web) via wasm-bindgen's `initSync({ module })`, instead of
// the default `init()` export's runtime `fetch(new URL('kbach_core_engine_bg.wasm',
// import.meta.url))`.
//
// That fetch-based path — the one @kbach/react's own wasmLoader.ts uses
// fine under Vite, since Vite's static-asset pipeline understands an
// import.meta.url-relative fetch of a co-located binary file — does NOT
// work under Metro (React Native's bundler, including Expo Web's Metro-based
// web build): Metro's asset system only tracks files reached through a
// statically-analyzable `require()`/`import`, and has no notion of a
// runtime `new URL(..., import.meta.url)` fetch at all, so the .wasm binary
// itself never gets copied into the bundled output directory — confirmed by
// hand: a real `expo export --platform web` + Playwright load reproduces a
// literal 404 fetching `.../kbach_core_engine_bg.wasm`. Embedding the bytes
// as a base64 JS string sidesteps Metro's asset pipeline entirely — it's
// just an ordinary (large) string constant Metro already knows how to
// bundle, no special resolver/asset config needed in any consuming app's
// metro.config.js.
//
// Usage: node generate-wasm-base64.mjs <output-path-relative-to-cwd>
// Run manually after `npm run build` regenerates dist/kbach_core_engine_bg.wasm
// — not wired into any prebuild/pretest hook, same reasoning as
// generate-palette.mjs in this same directory.

import { readFileSync, writeFileSync, mkdirSync } from 'fs';
import { dirname, join } from 'path';
import { fileURLToPath } from 'url';

const thisDir = dirname(fileURLToPath(import.meta.url));

const outputArg = process.argv[2];
if (!outputArg) {
  console.error('Usage: node generate-wasm-base64.mjs <output-path-relative-to-cwd>');
  process.exit(1);
}

const wasmPath = join(thisDir, '..', 'dist', 'kbach_core_engine_bg.wasm');
const bytes = readFileSync(wasmPath);
const base64 = bytes.toString('base64');

const outPath = join(process.cwd(), outputArg);
mkdirSync(dirname(outPath), { recursive: true });

writeFileSync(
  outPath,
  `// Generated by Kbach — do not edit.
// Regenerate: npm run generate:wasm-base64 (after changing Rust source and
// rebuilding core-engine's web-target WASM build — see
// packages/core-engine/scripts/generate-wasm-base64.mjs for why this exists
// at all instead of a plain fetched .wasm file).
export const KBACH_CORE_ENGINE_WASM_BASE64 = '${base64}';
`,
);

console.log(`Wrote ${outPath} (${bytes.length} bytes -> ${base64.length} base64 chars)`);
